#!/usr/bin/env node
/**
 * tsdb-structure.mjs
 *
 * Makes the Tessent Shell Database (tsdb_outdir) folder hierarchy visible in the graph.
 * The dashboard only groups nodes by the FIRST folder segment of a file path, so a flat list of
 * tsdb_outdir files shows up as one box. This module adds one `module` node per TSDB folder
 * (tsdb_outdir -> dft_inserted_designs / instruments / patterns / logic_test_cores -> the
 * <core>_<design_id>.<kind> object folders -> ATPG mode folders) plus `contains` edges, so the
 * graph shows the same path Tessent created.
 *
 * Each layer gets its own slice of the tree (folder ids are `folder:<layerId>:<path>`) containing
 * only the files that layer owns, because a node can belong to one layer only.
 *
 * Library:  import { addTsdbStructure } from './tsdb-structure.mjs'
 * CLI:      node tsdb-structure.mjs <knowledge-graph.json>      (post-process an existing graph in place;
 *                                                                 a .bak copy is written first)
 * Idempotent: existing folder nodes are left alone.
 */
import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';

const ROLE = [
  [/^tsdb_outdir$/, 'Tessent Shell Database (TSDB): everything Tessent writes during the flow, organised by object type. Objects are keyed by core name and design_id (for example rtl1, rtl2, gate), so a later stage can open an earlier stage\'s results.'],
  [/^dft_inserted_designs$/, 'Design snapshots after each DFT insertion pass, plus the DFT specification (*.dft_spec) that produced each one.'],
  [/\.dft_inserted_design$/, 'The design after one insertion pass (the design_id in the folder name): modified RTL or netlist, ICL / PDL / TCD descriptions, SDC, interface and graybox views, summary dictionaries.'],
  [/^instruments$/, 'Generated DFT instruments (IP). One *.instrument folder per instrument family per pass.'],
  [/_mbist\.instrument$/, 'MBIST instrument family: controller(s), memory interface(s) and the access port, each with RTL, ICL, PDL and core description, plus generation logs and memory models.'],
  [/_ijtag\.instrument$/, 'IJTAG instrument family: the SIBs and test data registers that form the access network.'],
  [/_occ\.instrument$/, 'OCC instrument family: on-chip clock controllers (RTL, ICL, PDL, core description, CTL).'],
  [/_edt\.instrument$/, 'EDT instrument family: scan-compression IP (decompressor, compactor, controller, bypass) with ICL, PDL and core description.'],
  [/_cells\.instrument$/, 'Helper cells generated alongside the instruments (for example reset synchronisers).'],
  [/\.instrument$/, 'Generated instrument folder (RTL, ICL, PDL, core description).'],
  [/^patterns$/, 'Pattern specifications and the signoff patterns generated from them.'],
  [/\.patterns_signoff$/, 'Signoff patterns generated from a patterns specification: per pattern entry a PDL, a Verilog testbench, vector and config files.'],
  [/^logic_test_cores$/, 'ATPG results per core and design_id.'],
  [/\.logic_test_core$/, 'ATPG database for one core at one design_id: one folder per ATPG mode (scan mode and fault model).'],
  [/atpg_retargeting_mode/, 'Retargeting mode: core description used to map a lower-level core\'s patterns to the parent\'s pins.'],
  [/\.atpg_mode_/, 'Result of one ATPG mode: core description (tcd), flattened model, fault list and pattern database.'],
];

function roleOf(seg) {
  for (const [re, text] of ROLE) if (re.test(seg)) return text;
  return 'Subfolder generated by Tessent inside the TSDB.';
}

function filePathOf(n) {
  if (n.filePath) return n.filePath;
  if (typeof n.id === 'string' && n.id.startsWith('file:')) return n.id.slice(5);
  return null;
}

/** Mutates and returns graph. */
export function addTsdbStructure(graph) {
  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  const added = { folders: 0, edges: 0 };
  const edgeKey = new Set(graph.edges.map((e) => `${e.source}|${e.target}|${e.type}`));
  const addEdge = (s, t, desc) => {
    const k = `${s}|${t}|contains`;
    if (edgeKey.has(k)) return;
    edgeKey.add(k);
    graph.edges.push({ source: s, target: t, type: 'contains', direction: 'forward', weight: 1, description: desc });
    added.edges++;
  };

  for (const layer of graph.layers) {
    const tsdbFiles = layer.nodeIds
      .map((id) => byId.get(id))
      .filter((n) => n && n.type === 'file')
      .map((n) => ({ n, path: filePathOf(n) }))
      .filter((x) => x.path && x.path.split('/').includes('tsdb_outdir'));
    if (tsdbFiles.length === 0) continue;

    // folderPath -> { children folder paths, file ids }
    const folders = new Map();
    const ensure = (p) => { if (!folders.has(p)) folders.set(p, { subs: new Set(), files: [] }); return folders.get(p); };
    for (const { n, path } of tsdbFiles) {
      const parts = path.split('/');
      const start = parts.indexOf('tsdb_outdir');
      let prev = null;
      for (let i = start; i < parts.length - 1; i++) {
        const p = parts.slice(0, i + 1).join('/');
        ensure(p);
        if (prev) ensure(prev).subs.add(p);
        prev = p;
      }
      if (prev) ensure(prev).files.push(n);
    }

    for (const p of folders.keys()) {
      const id = `folder:${layer.id}:${p}`;
      if (!byId.has(id)) {
        const seg = p.split('/').pop();
        const fileNames = collectFiles(folders, p).map((f) => f.name);
        const sample = fileNames.slice(0, 5).join(', ');
        const node = {
          id,
          type: 'module',
          name: seg === 'tsdb_outdir' ? 'tsdb_outdir (Tessent database)' : seg,
          filePath: p,
          summary: `${roleOf(seg)} In this stage: ${fileNames.length} file(s)${sample ? ` (${sample}${fileNames.length > 5 ? ', ...' : ''})` : ''}. Role inferred from Tessent's folder naming convention and the files inside.`,
          tags: ['tsdb', 'tsdb-folder', 'tessent-convention'],
          complexity: 'simple',
        };
        graph.nodes.push(node);
        byId.set(id, node);
        layer.nodeIds.push(id);
        added.folders++;
      }
    }
    for (const [p, info] of folders) {
      const id = `folder:${layer.id}:${p}`;
      for (const sub of info.subs) addEdge(id, `folder:${layer.id}:${sub}`, 'subfolder');
      for (const f of info.files) addEdge(id, f.id, 'file inside this TSDB folder');
    }
  }
  return { graph, added };
}

function collectFiles(folders, p) {
  const out = [];
  const info = folders.get(p);
  if (!info) return out;
  out.push(...info.files);
  for (const s of info.subs) out.push(...collectFiles(folders, s));
  return out;
}

// CLI
if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('/tsdb-structure.mjs')) {
  const target = process.argv[2];
  if (!target) {
    console.error('Usage: node tsdb-structure.mjs <knowledge-graph.json>');
    process.exit(2);
  }
  const g = JSON.parse(readFileSync(target, 'utf8'));
  const backup = target.replace(/\.json$/, '') + '.pre-tsdb.json';
  if (!existsSync(backup)) copyFileSync(target, backup); // keep the first (pre-structure) copy only
  const { added } = addTsdbStructure(g);
  writeFileSync(target, JSON.stringify(g, null, 2));
  console.log(`tsdb-structure: +${added.folders} folder nodes, +${added.edges} contains edges`);
}
